export function tt(key, vars = {}) {
  const dict = TT[getLang()] || TT.ru;
  const value = dict[key] ?? TT.ru[key] ?? key;
  return String(value).replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
