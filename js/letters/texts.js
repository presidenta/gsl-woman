export function lt(path, vars = {}) {
  let v = LT;
  for (const part of path.split('.')) v = v?.[part];
  if (typeof v !== 'string') return path;
  return v.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
