export const PROF_BY_ID = Object.fromEntries(PROFESSIONS.map((p) => [p.id, p]));
export const MAX_PROFESSIONS = 3;

/** Шаги маршрута с готовыми названиями: skill:id берёт название навыка из каталога. */
export function routeOf(profId) {
  const p = PROF_BY_ID[profId];
  if (!p) return [];
  return p.steps.map(([id, title]) => {
    if (id.startsWith('skill:')) {
      const s = SKILLS[id.slice(6)];
      return { id, title: s ? s.title : id, skill: s ? s.id : null };
    }
    return { id, title, skill: null };
  });
}

