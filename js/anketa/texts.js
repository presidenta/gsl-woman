const PACKS = { ru: RU, ua: UA, en: EN };

/** Язык анкеты сейчас: из <html lang> ('uk' → ua); в проверках (без страницы) — русский. */
export function anketaLang() {
  const l = globalThis.document?.documentElement?.lang || 'ru';
  return l === 'uk' || l === 'ua' ? 'ua' : l === 'en' ? 'en' : 'ru';
}

/** Надпись анкеты; vars — подстановки {name}. Нет на языке — русская. */
export function at(key, vars = {}) {
  let v = PACKS[anketaLang()][key] ?? RU[key];
  if (v && typeof v === 'object' && 'other' in v) v = v[vars.gender] || v.other; // слова по полу: { female, male, other }
  return typeof v === 'string' ? v.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`)) : v;
}
