/** Надпись анкеты; vars — подстановки {name}. Языков пока один — русский (страница гостя не грузит тексты приложения). */
export function at(key, vars = {}) {
  let v = RU[key];
  if (v && typeof v === 'object' && 'other' in v) v = v[vars.gender] || v.other; // слова по полу: { female, male, other }
  return typeof v === 'string' ? v.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`)) : v;
}
